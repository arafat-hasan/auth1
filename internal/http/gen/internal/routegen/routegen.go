package main

import (
	"bytes"
	"cmp"
	"errors"
	"fmt"
	"go/format"
	"slices"
	"strings"
	"text/template"

	"github.com/pb33f/libopenapi"
)

// scopeExtension names the scope a service operation requires (TDD-05 §3).
const scopeExtension = "x-auth1-scope"

// serviceSchemes are the security schemes that make an operation a service operation.
var serviceSchemes = []string{"workload", "serviceToken"}

// op is one served operation of the contract.
type op struct {
	ID       string
	Method   string   // upper case
	Path     string   // the path template, which is also the Chi pattern
	Scope    string   // x-auth1-scope; "" when there is none
	Security []string // the names of the schemes the operation accepts, sorted
}

// operations reads the served operations of an OpenAPI document, sorted by id, and checks the
// scope rules: a service operation has an x-auth1-scope, no other operation has one, and every
// scope is one of the serviceToken scheme's declared scopes. An operation that takes parameters
// or a body must also declare the 422 that a binding failure answers. Webhooks are left out: auth1 sends
// them, it does not serve them.
func operations(spec []byte) ([]op, error) {
	doc, err := libopenapi.NewDocument(spec)
	if err != nil {
		return nil, fmt.Errorf("parse the document: %w", err)
	}
	model, err := doc.BuildV3Model()
	if err != nil {
		return nil, fmt.Errorf("build the model: %w", err)
	}
	declared := map[string]bool{}
	if model.Model.Components != nil {
		if s, ok := model.Model.Components.SecuritySchemes.Get("serviceToken"); ok &&
			s.Flows != nil && s.Flows.ClientCredentials != nil {
			for scope := range s.Flows.ClientCredentials.Scopes.KeysFromOldest() {
				declared[scope] = true
			}
		}
	}

	var (
		ops  []op
		errs []error
	)
	if model.Model.Paths == nil {
		return nil, errors.New("the document has no paths")
	}
	for path, item := range model.Model.Paths.PathItems.FromOldest() {
		for method, o := range item.GetOperations().FromOldest() {
			cur := op{ID: o.OperationId, Method: strings.ToUpper(method), Path: path, Security: []string{}}
			if cur.ID == "" {
				errs = append(errs, fmt.Errorf("%s %s has no operationId", cur.Method, path))
				continue
			}
			for _, req := range o.Security {
				for name := range req.Requirements.KeysFromOldest() {
					if !slices.Contains(cur.Security, name) {
						cur.Security = append(cur.Security, name)
					}
				}
			}
			slices.Sort(cur.Security)
			if n, ok := o.Extensions.Get(scopeExtension); ok && n != nil {
				cur.Scope = n.Value
			}

			// gen.Routes answers a parameter or body it cannot bind with 422, so the operation must
			// declare it.
			binds := len(o.Parameters) > 0 || len(item.Parameters) > 0 || o.RequestBody != nil
			if binds && (o.Responses == nil || o.Responses.Codes.GetOrZero("422") == nil) {
				errs = append(errs, fmt.Errorf("%s: takes parameters or a body but does not declare 422", cur.ID))
			}

			service := slices.ContainsFunc(cur.Security, func(s string) bool { return slices.Contains(serviceSchemes, s) })
			switch {
			case service && cur.Scope == "":
				errs = append(errs, fmt.Errorf("%s: a service operation without %s", cur.ID, scopeExtension))
			case !service && cur.Scope != "":
				errs = append(errs, fmt.Errorf("%s: %s on an operation that is not a service operation", cur.ID, scopeExtension))
			case cur.Scope != "" && !declared[cur.Scope]:
				errs = append(errs, fmt.Errorf("%s: %s %q is not a scope of the serviceToken scheme", cur.ID, scopeExtension, cur.Scope))
			}
			ops = append(ops, cur)
		}
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	slices.SortFunc(ops, func(a, b op) int { return cmp.Compare(a.ID, b.ID) })
	return ops, nil
}

var routesTemplate = template.Must(template.New("routes").Parse(`// Code generated by routegen from api/openapi.yaml. DO NOT EDIT.

package gen

// Operation is the route metadata of one operation of api/openapi.yaml.
type Operation struct {
	Method   string   // the HTTP method
	Path     string   // the path template, which is also the Chi pattern below http.base_path
	Scope    string   // x-auth1-scope: the scope a service caller needs; "" for other operations
	Security []string // the security schemes the operation accepts; empty for a public one
}

// Operations maps each served operation's id to its route metadata.
var Operations = map[string]Operation{
{{- range .}}
	{{printf "%q" .ID}}: {Method: {{printf "%q" .Method}}, Path: {{printf "%q" .Path}}, Scope: {{printf "%q" .Scope}}, Security: []string{ {{- range $i, $s := .Security}}{{if $i}}, {{end}}{{printf "%q" $s}}{{end -}} }},
{{- end}}
}
`))

var stubTemplate = template.Must(template.New("stub").Funcs(template.FuncMap{"export": export}).Parse(`// Code generated by routegen from api/openapi.yaml. DO NOT EDIT.

package gen

import "context"

// Stub answers every operation with ErrNotImplemented. A handler embeds it, so that the
// operations it does not implement yet still satisfy StrictServerInterface.
type Stub struct{}
{{range .}}{{$n := export .ID}}
// {{$n}} returns ErrNotImplemented.
func (Stub) {{$n}}(context.Context, {{$n}}RequestObject) ({{$n}}ResponseObject, error) {
	return nil, ErrNotImplemented
}
{{end}}`))

// export returns the name oapi-codegen gives an operation id: its first letter in upper case.
func export(id string) string {
	return strings.ToUpper(id[:1]) + id[1:]
}

// routes returns the source of routes_gen.go.
func routes(ops []op) ([]byte, error) {
	return render(routesTemplate, ops)
}

// stub returns the source of stub_gen.go.
func stub(ops []op) ([]byte, error) {
	return render(stubTemplate, ops)
}

// render executes t on ops and formats the result as Go source.
func render(t *template.Template, ops []op) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, ops); err != nil {
		return nil, fmt.Errorf("execute the %s template: %w", t.Name(), err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format the %s source: %w", t.Name(), err)
	}
	return src, nil
}
